/* 电机 A（连接器 A）开环转动示例：
 *   方向:  IN1=PC12 / IN2=PC11（01 正转 / 10 反转 / 11 刹车 / 00 滑行）
 *   调速:  TIM1_CH2 (PA9) 占空比，ARR=1000 → 300 = 30% 占空比
 * 其他通道见《固件二次开发手册》引脚分配表。 */
static void demo_motor_a_spin(uint16_t duty /* 0~1000 */)
{
  if (duty > 1000) duty = 1000;
  HAL_GPIO_WritePin(GPIOC, GPIO_PIN_12, GPIO_PIN_SET);    /* IN1 = 1 */
  HAL_GPIO_WritePin(GPIOC, GPIO_PIN_11, GPIO_PIN_RESET);  /* IN2 = 0 */
  __HAL_TIM_SET_COMPARE(&htim1, TIM_CHANNEL_2, duty);     /* PWM */
}

